4.UPDATE SALES INFORMATION WITHOUT DUPLICATE SALE ID
DELIMITER //
CREATE PROCEDURE `SALESINFO`(IN P_SALEID INT,IN P_CUSTOMERID INT,IN P_EMPLOYEEID INT,IN P_SALEAMOUNT INT)
BEGIN
DECLARE NEWSALEID INT;
SELECT COUNT(*) 
INTO NEWSALEID FROM SALES
WHERE SALEID=P_SALEID;
IF NEWSALEID>0
THEN 
SIGNAL SQLSTATE'45000'
SET MESSAGE_TEXT='DUPLICATE_SALE';
ELSE
INSERT INTO SALES VALUES(P_SALEID,P_CUSTOMERID,P_EMPLOYEEID,P_SALEAMOUNT,CURDATE());
END IF;
END
