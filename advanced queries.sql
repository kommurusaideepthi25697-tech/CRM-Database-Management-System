CREATE TRIGGER RevenueAutomation
AFTER INSERT ON Sales
FOR EACH ROW
BEGIN
    UPDATE Opportunities
    SET Stage='Closed Won'
    WHERE CustomerID=NEW.CustomerID;
END //

